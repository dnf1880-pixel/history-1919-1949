/* ---- 便捷查询 ---- */
window.SITE.getEvent = function (id) {
  for (var i = 0; i < window.EVENTS.length; i++) {
    if (window.EVENTS[i].id === id) return window.EVENTS[i];
  }
  return null;
};

window.SITE.getNeighbors = function (id) {
  var list = window.EVENTS;
  for (var i = 0; i < list.length; i++) {
    if (list[i].id === id) {
      return { prev: i > 0 ? list[i - 1] : null, next: i < list.length - 1 ? list[i + 1] : null };
    }
  }
  return { prev: null, next: null };
};

window.SITE.getStage = function (key) {
  for (var i = 0; i < window.STAGES.length; i++) {
    if (window.STAGES[i].key === key) return window.STAGES[i];
  }
  return null;
};

window.SITE.eventsOfStage = function (key) {
  return window.EVENTS.filter(function (e) { return e.stage === key; });
};
